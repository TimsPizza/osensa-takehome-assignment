import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { jsonSchemaToZod } from 'json-schema-to-zod';
import { format, resolveConfig } from 'prettier';

const frontendDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const backendDirectory = resolve(frontendDirectory, '..', 'backend');
const outputPath = resolve(frontendDirectory, 'src', 'lib', 'generated', 'contracts.ts');
const checkOnly = process.argv.includes('--check');

const exported = spawnSync('uv', ['run', 'python', '-m', 'scripts.export_contracts'], {
	cwd: backendDirectory,
	encoding: 'utf8'
});

if (exported.status !== 0) {
	process.stderr.write(exported.stderr);
	process.exit(exported.status ?? 1);
}

const document = JSON.parse(exported.stdout);
if (!Array.isArray(document.models)) {
	throw new Error('Backend contract export did not contain a models array');
}

const generatedModels = document.models.map(({ name, schema }) => {
	if (typeof name !== 'string' || typeof schema !== 'object' || schema === null) {
		throw new Error('Backend contract export contained an invalid model entry');
	}

	const zodExpression = jsonSchemaToZod(schema);
	return [
		`export const ${name}Schema = ${zodExpression};`,
		`export type ${name} = z.infer<typeof ${name}Schema>;`
	].join('\n');
});

const source = [
	'// This file is generated by `pnpm contract:gen`. Do not edit manually.',
	"import { z } from 'zod';",
	...generatedModels
].join('\n\n');

const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const formatted = await format(source, {
	...prettierConfig,
	filepath: outputPath
});

if (checkOnly) {
	if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== formatted) {
		process.stderr.write(
			'Generated MQTT contracts are stale. Run `pnpm contract:gen` in frontend.\n'
		);
		process.exit(1);
	}
	process.stdout.write('Generated MQTT contracts are up to date.\n');
} else {
	mkdirSync(dirname(outputPath), { recursive: true });
	writeFileSync(outputPath, formatted);
	process.stdout.write(`Generated ${document.models.length} contracts at ${outputPath}\n`);
}
